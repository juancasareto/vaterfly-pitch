/* Motor de idiomas. Lee los atributos data-i18n* y los reemplaza según el idioma.
   El español original se captura del HTML la primera vez que se toca cada elemento. */
(function(){
  var LANGS = ['es', 'en', 'pt', 'ko'];
  var STORE = 'vaterflyLang';
  var KO_FONT = 'https://fonts.googleapis.com/css2?family=Noto+Sans+KR:wght@400;700;900&display=swap';
  var dict = window.VF_DICT || {};
  var originals = {};
  var current = 'es';

  var ATTRS = [
    ['data-i18n', function(el){ return el.innerHTML; }, function(el, v){ el.innerHTML = v; }],
    ['data-i18n-placeholder', function(el){ return el.getAttribute('placeholder'); }, function(el, v){ el.setAttribute('placeholder', v); }],
    ['data-i18n-aria', function(el){ return el.getAttribute('aria-label'); }, function(el, v){ el.setAttribute('aria-label', v); }],
    ['data-i18n-alt', function(el){ return el.getAttribute('alt'); }, function(el, v){ el.setAttribute('alt', v); }],
    ['data-i18n-text', function(el){ return el.getAttribute('data-text'); }, function(el, v){ el.setAttribute('data-text', v); }]
  ];

  function detect(){
    try {
      var saved = localStorage.getItem(STORE);
      if (LANGS.indexOf(saved) > -1) return saved;
    } catch(e) {}
    var list = navigator.languages || [navigator.language || 'es'];
    for (var i = 0; i < list.length; i++) {
      var code = String(list[i]).slice(0, 2).toLowerCase();
      if (LANGS.indexOf(code) > -1) return code;
    }
    return 'en';
  }

  function applyTo(root){
    ATTRS.forEach(function(a){
      var nodes = root.querySelectorAll('[' + a[0] + ']');
      for (var i = 0; i < nodes.length; i++) {
        var el = nodes[i];
        var key = el.getAttribute(a[0]);
        var id = a[0] + ':' + key;
        if (!(id in originals)) originals[id] = a[1](el);
        var val = current === 'es' ? originals[id] : (dict[current] && dict[current][key]);
        if (val == null) val = originals[id];
        a[2](el, val);
      }
    });
  }

  function syncButtons(){
    var btns = document.querySelectorAll('[data-lang]');
    for (var i = 0; i < btns.length; i++) {
      var on = btns[i].getAttribute('data-lang') === current;
      btns[i].classList.toggle('active', on);
      btns[i].setAttribute('aria-pressed', on ? 'true' : 'false');
    }
  }

  function ensureKoFont(){
    if (document.getElementById('vfKoFont')) return;
    var link = document.createElement('link');
    link.id = 'vfKoFont';
    link.rel = 'stylesheet';
    link.href = KO_FONT;
    document.head.appendChild(link);
  }

  function setLang(lang, persist){
    if (LANGS.indexOf(lang) < 0) lang = 'es';
    current = lang;
    document.documentElement.lang = lang;
    if (lang === 'ko') ensureKoFont();
    applyTo(document);
    syncButtons();
    if (persist) { try { localStorage.setItem(STORE, lang); } catch(e) {} }
    document.dispatchEvent(new CustomEvent('vf:langchange', { detail: { lang: lang } }));
  }

  document.addEventListener('click', function(e){
    var btn = e.target.closest && e.target.closest('[data-lang]');
    if (!btn) return;
    e.preventDefault();
    setLang(btn.getAttribute('data-lang'), true);
  });

  current = detect();
  window.VF_LANG = {
    init: function(){ setLang(current, false); },
    set: function(lang){ setLang(lang, true); },
    get: function(){ return current; }
  };

  document.addEventListener('DOMContentLoaded', function(){ setLang(current, false); });
})();
